BEGIN TRANSACTION;
CREATE TABLE IF NOT EXISTS "Actor" (
	"ID_ACTOR"	INTEGER,
	"Nombre_Actor"	TEXT,
	"Apellido_Actor"	TEXT,
	"Animado"	TEXT,
	PRIMARY KEY("ID_ACTOR" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Calificacion" (
	"ID_CALIFICACION"	INTEGER,
	"Tipo_Calificacion"	INTEGER,
	PRIMARY KEY("ID_CALIFICACION" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Cine" (
	"ID_CINE"	INTEGER,
	"Nombre_Cine"	TEXT,
	"Direccion"	TEXT,
	PRIMARY KEY("ID_CINE" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Entrada" (
	"ID_ENTRADA"	INTEGER,
	"Numero_Entrada"	NUMERIC,
	"Fecha_Hora_Venta"	NUMERIC,
	"Fecha_Hora_Funcion"	NUMERIC,
	"Precio_Cobrado"	NUMERIC,
	"ID_PELICULA"	INTEGER,
	"ID_FUNCION"	INTEGER,
	"ID_SALA"	INTEGER,
	PRIMARY KEY("ID_ENTRADA" AUTOINCREMENT),
	FOREIGN KEY("ID_FUNCION") REFERENCES "Funcion"("ID_FUNCION "),
	FOREIGN KEY("ID_PELICULA") REFERENCES "Pelicula"("ID_PELICULA"),
	FOREIGN KEY("ID_SALA") REFERENCES "Sala"("ID_SALA")
);
CREATE TABLE IF NOT EXISTS "Funcion" (
	"ID_FUNCION "	INTEGER NOT NULL,
	"Dia_Semana"	NUMERIC,
	"Hora_Inicio"	NUMERIC,
	"Duracion"	NUMERIC,
	"ID_CINE "	INTEGER NOT NULL,
	"ID_SALA "	INTEGER NOT NULL,
	"ID_PELICULA "	INTEGER NOT NULL,
	"ID_PROGRAMACION "	INTEGER NOT NULL,
	PRIMARY KEY("ID_FUNCION " AUTOINCREMENT),
	FOREIGN KEY("ID_CINE ") REFERENCES "Cine"("ID_CINE"),
	FOREIGN KEY("ID_PELICULA ") REFERENCES "Pelicula"("ID_PELICULA"),
	FOREIGN KEY("ID_PROGRAMACION ") REFERENCES "Programacion"("ID_PROGRAMACION"),
	FOREIGN KEY("ID_SALA ") REFERENCES "Sala"("ID_SALA")
);
CREATE TABLE IF NOT EXISTS "Genero" (
	"ID_GENERO"	INTEGER,
	"Tipo_Genero"	TEXT,
	PRIMARY KEY("ID_GENERO" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "País de Origen" (
	"ID_PAIS_ORIGEN"	INTEGER,
	"Nombre_Pais"	TEXT,
	"Idioma"	TEXT,
	PRIMARY KEY("ID_PAIS_ORIGEN" AUTOINCREMENT)
);
CREATE TABLE IF NOT EXISTS "Pelicula" (
	"ID_PELICULA"	INTEGER,
	"Nombre_Pelicula"	TEXT,
	"Año_Estreno"	NUMERIC,
	"Duracion"	NUMERIC,
	"Fecha_Ingreso"	NUMERIC,
	"Disponibilidad"	TEXT,
	"ID_GENERO "	INTEGER,
	"ID_CALIFICACION"	INTEGER,
	"ID_PAIS_DE_ORIGEN"	INTEGER, Titulo TEXT, Descripcion TEXT, Imagen TEXT,
	PRIMARY KEY("ID_PELICULA" AUTOINCREMENT),
	FOREIGN KEY("ID_CALIFICACION") REFERENCES "Cine"("ID_CINE"),
	FOREIGN KEY("ID_GENERO ") REFERENCES "Genero"("ID_GENERO"),
	FOREIGN KEY("ID_PAIS_DE_ORIGEN") REFERENCES "País de Origen"("ID_PAIS_ORIGEN")
);
CREATE TABLE IF NOT EXISTS "Personaje" (
	"ID_PERSONAJE"	INTEGER,
	"Nombre_Personaje"	TEXT,
	"ID_ACTOR"	INTEGER,
	PRIMARY KEY("ID_PERSONAJE" AUTOINCREMENT),
	FOREIGN KEY("ID_ACTOR") REFERENCES "Actor"("ID_ACTOR")
);
CREATE TABLE IF NOT EXISTS "Programacion" (
	"ID_PROGRAMACION"	INTEGER,
	"Fecha_Inicio"	NUMERIC,
	"Fecha_Fin"	NUMERIC,
	"Fecha_Hora_Creada"	NUMERIC,
	"ID_CINE"	INTEGER,
	PRIMARY KEY("ID_PROGRAMACION" AUTOINCREMENT),
	FOREIGN KEY("ID_CINE") REFERENCES "Cine"("ID_CINE")
);
CREATE TABLE IF NOT EXISTS "Reparto" (
	"ID_REPARTO"	INTEGER,
	"ID_PELICULA"	INTEGER,
	"ID_PERSONAJE"	INTEGER,
	PRIMARY KEY("ID_REPARTO" AUTOINCREMENT),
	FOREIGN KEY("ID_PELICULA") REFERENCES "Pelicula"("ID_PELICULA"),
	FOREIGN KEY("ID_PERSONAJE") REFERENCES "Personaje"("ID_PERSONAJE")
);
CREATE TABLE IF NOT EXISTS "Sala" (
	"ID_SALA"	INTEGER,
	"Numero"	NUMERIC,
	"Capacidad"	NUMERIC,
	"ID_CINE"	INTEGER, Filas INTEGER, Butacasporfila INTEGER,
	PRIMARY KEY("ID_SALA" AUTOINCREMENT),
	FOREIGN KEY("ID_CINE") REFERENCES "Cine"
);
COMMIT;
